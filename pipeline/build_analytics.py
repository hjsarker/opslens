"""Build reproducible SQL-powered reporting aggregates for OpsLens.

Runs with Python's built-in SQLite. If DuckDB is installed, --engine duckdb
runs the same parameterized SQL against DuckDB. No JS-side KPI estimates are
needed for the published dashboard; JSON aggregates are generated by SQL.
"""
from __future__ import annotations
import argparse
import copy
import json
import sqlite3
from collections import Counter
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
DATA=ROOT/'data'
CATEGORIES=['P1','P2','P3','P4']
RANGES=(30,90,365,0)
DAY=86400

def epoch(iso):return datetime.fromisoformat(iso.replace('Z','+00:00')).timestamp() if iso else None

def connection(engine):
    if engine=='duckdb':
        try:import duckdb
        except ImportError as e:raise RuntimeError('Install optional dependency: pip install duckdb') from e
        return duckdb.connect(':memory:')
    return sqlite3.connect(':memory:')

def run(sql,db,params=()):
    cursor=db.execute(sql,params)
    keys=[x[0] for x in cursor.description]
    return [dict(zip(keys,row)) for row in cursor.fetchall()]

def load(db,incidents):
    db.execute('''CREATE TABLE incidents (
        id VARCHAR PRIMARY KEY, opened_epoch DOUBLE, resolved_epoch DOUBLE,
        priority VARCHAR, status VARCHAR, category VARCHAR, service VARCHAR,
        team VARCHAR, summary VARCHAR, sla_status VARCHAR, sla_percent DOUBLE,
        sla_used_min DOUBLE, sla_target_min DOUBLE, resolution_minutes DOUBLE,
        reassignments INTEGER, hold_count INTEGER, issue_key VARCHAR)''')
    db.execute('''CREATE TABLE incident_events(
      event_id VARCHAR PRIMARY KEY, incident_id VARCHAR, at_epoch DOUBLE,
      event_type VARCHAR, team VARCHAR)''')
    db.executemany('INSERT INTO incidents VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)', [
        (x['id'],epoch(x['openedAt']),epoch(x['resolvedAt']),x['priority'],x['status'],
         x['category'],x['service'],x['team'],x['summary'],x['slaStatus'],x['slaPercent'],
         x['slaUsedMin'],x['slaTargetMin'],x['resolutionMinutes'],x['reassignments'],x['holds'],
         (x['service']+' | '+x['summary']).lower()) for x in incidents
    ])
    db.executemany('INSERT INTO incident_events VALUES (?,?,?,?,?)',[
        (ev['id'],x['id'],epoch(ev['at']),ev['type'],ev['team'])
        for x in incidents for ev in x['events']
    ])
    db.execute('CREATE INDEX idx_inc_open ON incidents(opened_epoch)')
    db.execute('CREATE INDEX idx_inc_resolved ON incidents(resolved_epoch)')
    db.execute('CREATE INDEX idx_inc_service ON incidents(service)')
    return db

def metrics(db,cutoff,asof):
    op=run('''SELECT COUNT(*) opened FROM incidents WHERE opened_epoch >= ? AND opened_epoch <= ?''',db,(cutoff,asof))[0]['opened']
    resolved=run('''SELECT COUNT(*) resolved,
       SUM(CASE WHEN sla_status='Met' THEN 1 ELSE 0 END) compliant,
       AVG(resolution_minutes) mttr_minutes
       FROM incidents WHERE resolved_epoch >= ? AND resolved_epoch <= ?''',db,(cutoff,asof))[0]
    resol=resolved['resolved']
    categories=run('''SELECT category AS name, COUNT(*) AS count FROM incidents
      WHERE opened_epoch >= ? AND opened_epoch <= ? GROUP BY category ORDER BY count DESC,name''',db,(cutoff,asof))
    priorities=run('''SELECT priority AS name, COUNT(*) AS count FROM incidents
      WHERE opened_epoch >= ? AND opened_epoch <= ? GROUP BY priority ORDER BY name''',db,(cutoff,asof))
    teams=run('''SELECT team AS name,
        COUNT(*) FILTER (WHERE opened_epoch >= ? AND opened_epoch <= ?) AS opened,
        COUNT(*) FILTER (WHERE resolved_epoch >= ? AND resolved_epoch <= ?) AS resolved,
        SUM(CASE WHEN resolved_epoch >= ? AND resolved_epoch <= ? AND sla_status='Met' THEN 1 ELSE 0 END) AS met,
        AVG(CASE WHEN resolved_epoch >= ? AND resolved_epoch <= ? THEN resolution_minutes END) AS mttrMinutes,
        AVG(CASE WHEN opened_epoch >= ? AND opened_epoch <= ? THEN reassignments END) AS avgTransfers
        FROM incidents GROUP BY team ORDER BY opened DESC,name''',db,(cutoff,asof,cutoff,asof,cutoff,asof,cutoff,asof,cutoff,asof))
    for row in teams:
        row['compliance']=round((row['met'] or 0)*100/row['resolved'],1) if row['resolved'] else None
        row['mttrMinutes']=round(row['mttrMinutes'] or 0,1)
        row['avgTransfers']=round(row['avgTransfers'] or 0,2)
    services=run('''SELECT service AS name, category, COUNT(*) FILTER (WHERE opened_epoch>=? AND opened_epoch<=?) opened,
         COUNT(*) FILTER (WHERE resolved_epoch>=? AND resolved_epoch<=?) resolved,
         SUM(CASE WHEN resolved_epoch>=? AND resolved_epoch<=? AND sla_status='Met' THEN 1 ELSE 0 END) met,
         AVG(CASE WHEN resolved_epoch>=? AND resolved_epoch<=? THEN resolution_minutes END) mttrMinutes,
         AVG(CASE WHEN opened_epoch>=? AND opened_epoch<=? THEN reassignments END) avgTransfers
         FROM incidents GROUP BY service,category ORDER BY opened DESC,name''',db,(cutoff,asof,cutoff,asof,cutoff,asof,cutoff,asof,cutoff,asof))
    for row in services:
        row['compliance']=round((row['met'] or 0)*100/row['resolved'],1) if row['resolved'] else None
        row['mttrMinutes']=round(row['mttrMinutes'] or 0,1)
        row['avgTransfers']=round(row['avgTransfers'] or 0,2)
    issues=run('''SELECT summary AS name, service, COUNT(*) AS count,
          AVG(reassignments) AS avgTransfers
          FROM incidents WHERE opened_epoch>=? AND opened_epoch<=?
          GROUP BY summary,service ORDER BY count DESC,name LIMIT 16''',db,(cutoff,asof))
    for row in issues:row['avgTransfers']=round(row['avgTransfers'] or 0,2)
    return {
       'opened':op,'resolved':resol,'met':resolved['compliant'] or 0,
       'compliance':round((resolved['compliant'] or 0)*100/resol,1) if resol else None,
       'mttrMinutes':round(resolved['mttr_minutes'] or 0,1),
       'categories':categories,'priorities':priorities,'teams':teams,'services':services,
       'issues':issues
    }

def backlog(db,asof):
    # Real as-of reconstruction: open on each date if opened before date end
    # and not yet resolved as of that date. Snapshot is fixed and reproducible.
    result=[]
    start=datetime.fromtimestamp(asof,tz=timezone.utc).date()-timedelta(days=366)
    for n in range(367):
        date=start+timedelta(days=n)
        end=datetime.combine(date+timedelta(days=1),datetime.min.time(),tzinfo=timezone.utc).timestamp()-1
        end=min(end,asof)
        rows=run('''SELECT COUNT(*) AS total FROM incidents
          WHERE opened_epoch<=? AND (resolved_epoch IS NULL OR resolved_epoch>?)''',db,(end,end))
        result.append({'date':date.isoformat(),'count':rows[0]['total']})
    return result

def quality_checks(records):
    """Return record-level violations and totals, independently of generator asserts."""
    ids=set();violations=[]
    def issue(x,rule,details):violations.append({'id':x.get('id','?'),'rule':rule,'details':details})
    for x in records:
        ident=x.get('id','?')
        if ident in ids:issue(x,'duplicate_id','Incident identifier repeated')
        ids.add(ident)
        for key in ('priority','category','service','team','summary'):
            if not x.get(key):issue(x,'required_field',f'Missing {key}')
        start=epoch(x.get('openedAt')) if x.get('openedAt') else None
        end=epoch(x.get('resolvedAt')) if x.get('resolvedAt') else None
        if start is None or end is not None and end<start:issue(x,'timestamp','Resolution earlier than opening')
        if x.get('status') in ('Closed','Resolved') and end is None:issue(x,'state','Completed without resolution timestamp')
        events=x.get('events') or []
        if not events:issue(x,'event_history','Missing incident events')
        else:
            stamps=[epoch(ev['at']) for ev in events]
            if stamps!=sorted(stamps) or (start is not None and stamps[0]<start):issue(x,'event_history','Invalid event ordering')
            if sum(ev['type']=='reassigned' for ev in events)!=x.get('reassignments'):issue(x,'assignment','Transfer count mismatch')
        if x.get('slaTargetMin',0)<=0 or x.get('slaPercent',-1)<0:issue(x,'sla','Invalid SLA target or consumption')
    rules=['duplicate_id','required_field','timestamp','state','event_history','assignment','sla']
    counts=Counter(v['rule'] for v in violations)
    return {'checked':len(records),'passed':len(records)-len(set(v['id'] for v in violations)),
        'failed':len(set(v['id'] for v in violations)),
        'rules':[{'id':r,'count':counts[r]} for r in rules],
        'violations':violations[:100]}

def example_bad_records(records):
    """Isolated, deliberately broken mock rows for teaching validation.

    These never enter the incident fact table or dashboard denominators.
    """
    scenarios=[]
    for index,(rule,description) in enumerate([
        ('required_field','Service omitted from the ticket'),
        ('timestamp','Resolution earlier than creation'),
        ('state','Completed incident missing resolution timestamp'),
        ('event_history','Event list is out of chronological order'),
        ('assignment','Team transfer count does not match events'),
        ('sla','SLA target is negative'),
    ]):
        x=copy.deepcopy(records[index+10])
        x['id']=f'TEST-BAD-{index+1:03d}'
        if rule=='required_field':x['service']=''
        elif rule=='timestamp':x['resolvedAt']='2020-01-01T00:00:00Z'
        elif rule=='state':x['status']='Resolved';x['resolvedAt']=None
        elif rule=='event_history':x['events']=list(reversed(x['events']))
        elif rule=='assignment':x['reassignments']=x['reassignments']+3
        elif rule=='sla':x['slaTargetMin']=-1
        actual=quality_checks([x])
        scenarios.append({'id':x['id'],'scenario':description,'expectedRule':rule,
                          'detected':any(v['rule']==rule for v in actual['violations']),
                          'diagnostic':next((v['details'] for v in actual['violations'] if v['rule']==rule),'Not detected')})
    first=copy.deepcopy(records[20]);first['id']='TEST-BAD-DUPLICATE'
    second=copy.deepcopy(first)
    dup=quality_checks([first,second])
    scenarios.append({'id':'TEST-BAD-DUPLICATE','scenario':'Duplicate incident IDs',
                       'expectedRule':'duplicate_id',
                       'detected':any(v['rule']=='duplicate_id' for v in dup['violations']),
                       'diagnostic':'Incident identifier repeated'})
    return scenarios

def build(engine='sqlite',path=DATA/'incidents.json',write=True):
    data=json.loads(Path(path).read_text(encoding='utf8'))
    db=load(connection(engine),data['incidents'])
    asof=epoch(data['meta']['asOf'])
    ranges={str(days):metrics(db,asof-days*DAY if days else 0,asof) for days in RANGES}
    openStats=run('''SELECT COUNT(*) AS open, SUM(CASE WHEN sla_status IN ('At risk','Critical','Breached') THEN 1 ELSE 0 END) attention,
           SUM(CASE WHEN sla_status='Breached' THEN 1 ELSE 0 END) AS breached
           FROM incidents WHERE resolved_epoch IS NULL''',db)[0]
    aggregate={
      'meta':{'asOf':data['meta']['asOf'],'engine':engine,'synthetic':True,
             'sourceIncidents':len(data['incidents']),'generatedFrom':'parameterized SQL queries'},
      'current':{'open':openStats['open'],'attention':openStats['attention'] or 0,'breached':openStats['breached'] or 0},
      'ranges':ranges,'backlogDaily':backlog(db,asof),
      'quality':quality_checks(data['incidents']),
      'qualityScenarios':example_bad_records(data['incidents']),
    }
    if write:
        target=DATA/'analytics.json';target.write_text(json.dumps(aggregate,ensure_ascii=False,separators=(',',':'))+'\n',encoding='utf8')
        print(f'Wrote {target}, {target.stat().st_size} bytes ({engine} SQL)')
    db.close()
    return aggregate

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--engine',choices=['sqlite','duckdb'],default='sqlite');args=p.parse_args()
    build(args.engine)
